import pathlib, json, hashlib, subprocess, shutil

B = pathlib.Path(__file__).resolve().parent
OBJ = B.parent.parent
W = OBJ.parents[5]
P = OBJ / 'candidates/round-03/packet.json'
R = OBJ / 'reviews/round-03.json'
M = B / 'manifest.json'
S = B / 'seal.json'
G = OBJ / 'reviews/round-03-acceptance.log'
VALIDATOR = W / 'prototypes/sushi-loop/assets/refinement/tools/acceptance_contract.py'

def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()

def write(p, data):
    p.write_text(json.dumps(data, indent=2) + '\n')

assert not any(p.exists() for p in [R, M, S, G]), 'Never overwrite a signed review'
review = json.loads((B / 'review-content.json').read_text())
assert review['verdict'] == 'approve' and review['blockers'] == []
assert sha(P) == review['candidatePacketSHA256'] == '33fe55a048751dee3457db79b05a7a070224ffb813ab532df8e90bea0fbd7682'
assert sha(OBJ / 'source/round-03.blend') == sha(B / 'resources/source.blend') == review['candidateProjectSHA256']
assert sha(OBJ / 'reviews/round-02.json') == 'f8ae79b19353df926fc72d0a77c0b8b4c0787bfb0534348063e13cee9f9d470f'
assert sha(OBJ / 'reviews/round-02-independent/manifest.json') == '6fc6d704239486916a8dbba376ab205ac705fa7144ffb8e952a2d76c8423d5b3'
assert sha(B / 'resources/brief.json') == '708eb790e6ba8e5c81287fa7ad3589bbb24a733922c197a7104c7e3ed0533275'
assert sha(B / 'resources/root-native-contract.json') == '00de726dbd7b195ae6b3322e07e4fcb2b62ecf342f3ec90c5390db799a788742'
assert sha(B / 'resources/criteria.json') == 'ea0a7afbb9c7a252ba65bcdcca1c8c8dbc671245cf0511417a96fedb85adb58f'
assert sha(VALIDATOR) == sha(B / 'resources/acceptance_contract.py')
packet = json.loads(P.read_text())
assert set(review['inspectedFiles']) == {r['path'] for g in ['candidateRenders', 'previews'] for r in packet[g].values()}
cache = {}
for group in ['files', 'candidateRenders', 'previews']:
    for record in packet[group].values():
        p = (P.parent / record['path']).resolve()
        if p not in cache:
            cache[p] = sha(p)
        assert cache[p] == record['sha256'], str(p)
checks = json.loads((B / 'evidence/technical-checks.json').read_text())
assert all(checks['checks'].values())
assert json.loads((B / 'evidence/packet-verification.json').read_text())['allMatch']
assert json.loads((B / 'evidence/consumer-results.json').read_text())['errors'] == []
for record in json.loads((B / 'resources/sealed-render-bindings.json').read_text()):
    assert sha(OBJ / record['original']) == sha(OBJ / record['copy']) == record['sha256']
for record in json.loads((B / 'resources/external-runtime-identities.json').read_text())['runtimeFiles']:
    assert sha(pathlib.Path(record['path'])) == record['sha256'], record['path']

files = []
for p in sorted(B.rglob('*')):
    if p.is_file() and p not in [M, S]:
        assert p.stat().st_size < 100000000 and '__pycache__' not in p.parts
        files.append({'path': str(p.relative_to(OBJ)), 'sha256': sha(p), 'bytes': p.stat().st_size})
manifest = {
    'schema': 'independent-judge-supplement-v1', 'asset': 'rock-shelf-middle', 'round': 'round-03',
    'candidatePacketSHA256': sha(P), 'sourceSHA256': review['candidateProjectSHA256'], 'files': files,
    'scope': 'Original independent judge full current art/technical review of exact round03. Exact candidate/source/inputs/preparation/prior signed bytes unchanged. Actual saved-source reopen, finite ports/base/envelope/camera, endpoint normal-albedo fields, static resources, whole BOX, all declared media and independently captured actual consumer checked. No art edits, source save, family or promotion approval.',
    'resourceClosure': 'Exact current/prior native sources and packet/frozen brief/criteria/contract/references/instructions, sealed native single/strip and published inputs, copied actual current and historical consumer helpers, independent scripts with retained failed comparison diagnostics, minimal executable Pillow/Playwright closure, actual reopens/strips/measurements/browser captures. Full runtime trees not duplicated; external binary identities pinned.',
    'acceptanceLog': 'reviews/round-03-acceptance.log is generated by the unchanged strict gate after this manifest and final verdict exist; seal.json binds all three to avoid a hash cycle. Neither verdict nor manifest is edited after that gate.'
}
write(M, manifest)
review['supplementalEvidence'] = {'path': 'reviews/round-03-independent/manifest.json', 'sha256': sha(M)}
write(R, review)
final_review_sha = sha(R)
command = ['python3', 'prototypes/sushi-loop/assets/refinement/tools/acceptance_contract.py', 'rock-shelf-middle', '--round', 'round-03']
result = subprocess.run(command, cwd=W, text=True, capture_output=True)
G.write_text('$ ' + ' '.join(command) + '\nValidatorSHA256=' + sha(VALIDATOR) + '\n'
             + result.stdout + result.stderr + 'ExitCode=' + str(result.returncode) + '\n')
assert result.returncode == 0, 'Unchanged strict acceptance failed; no sealed approval handoff'
gate = json.loads(result.stdout)
assert gate['method'] == 'independent-review' and gate['asset'] == 'rock-shelf-middle' and gate['sha256'] == final_review_sha
assert sha(R) == final_review_sha and sha(P) == review['candidatePacketSHA256']
assert sha(OBJ / 'source/round-03.blend') == review['candidateProjectSHA256']
write(S, {
    'asset': 'rock-shelf-middle', 'round': 'round-03', 'verdict': 'approve',
    'candidatePacketSHA256': sha(P), 'sourceSHA256': review['candidateProjectSHA256'],
    'review': str(R.relative_to(OBJ)), 'reviewSHA256': final_review_sha,
    'supplementalEvidence': {'path': str(M.relative_to(OBJ)), 'sha256': sha(M)},
    'acceptanceGate': {'path': str(G.relative_to(OBJ)), 'sha256': sha(G), 'validatorSHA256': sha(VALIDATOR), 'exitCode': 0, 'reviewSHA256': gate['sha256']},
    'files': len(files), 'bytes': sum(v['bytes'] for v in files),
    'immutable': 'No post-gate review/source/candidate edits. Keep this exact verdict/manifest/evidence/gate immutable; later changes require new versioned candidate/review.',
    'approvalScope': review['approvalScope']
})
print(json.dumps(json.loads(S.read_text()), indent=2))
